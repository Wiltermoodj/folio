import type { FolioData, FolioReportMeta } from '../types/folio';

/**
 * Formats a FolioData object as a clean JSON string.
 */
export function formatFolioDataAsJson(data: FolioData): string {
  return JSON.stringify(data, null, 2);
}

/**
 * Formats a FolioData object as the exact `const DATA = { ... };` block used inside index.html.
 */
export function formatFolioDataAsJsBlock(data: FolioData, indentSpaces = 4): string {
  const json = JSON.stringify(data, null, 2);
  const pad = ' '.repeat(indentSpaces);
  const indented = json
    .split('\n')
    .map((line, idx) => (idx === 0 ? line : pad + line))
    .join('\n');
  return `${pad}const DATA = ${indented};`;
}

/**
 * Formats a FolioData object as a strongly-typed TypeScript module (`folio-data.ts`).
 */
export function formatFolioDataAsTypeScript(data: FolioData, meta?: FolioReportMeta): string {
  const metaBlock = meta
    ? `\nexport const REPORT_META = ${JSON.stringify(meta, null, 2)} as const;\n`
    : '';
  return `/**
 * Auto-generated by Folio TypeScript Data Importer
 * Compatible with index.html interactive dashboard template
 */
import type { FolioData } from './types/folio';
${metaBlock}
export const DATA: FolioData = ${JSON.stringify(data, null, 2)};

export default DATA;
`;
}

/**
 * Generates a 100% standalone, zero-dependency index.html file in the exact format of index.html,
 * embedding the user's imported DATA and report metadata.
 */
export function generateStandaloneIndexHtml(
  templateHtml: string,
  data: FolioData,
  meta: FolioReportMeta
): string {
  let html = templateHtml;

  // 1. Remove any external module script tag for the Studio workbench if exporting pure standalone report,
  // or replace the inline/embedded DATA block so the exported HTML works offline anywhere.
  const jsBlock = `window.__FOLIO_CUSTOM_DATA__ = ${JSON.stringify(data, null, 2)};\n    window.__FOLIO_CUSTOM_META__ = ${JSON.stringify(meta, null, 2)};`;

  if (html.includes('/* __FOLIO_DATA_INJECTION_POINT__ */')) {
    html = html.replace('/* __FOLIO_DATA_INJECTION_POINT__ */', jsBlock);
  }

  // Also replace `const DATA = { ... };` block if present in templateHtml
  const dataRegex = /const\s+DATA\s*=\s*\{[\s\S]*?\n\s{4}\};/;
  if (dataRegex.test(html)) {
    html = html.replace(dataRegex, formatFolioDataAsJsBlock(data, 4).trimStart());
  }

  return html;
}
